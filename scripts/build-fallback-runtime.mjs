import {createHash} from 'node:crypto';
import {readFile, writeFile} from 'node:fs/promises';
import {watch} from 'node:fs';
import {fileURLToPath} from 'node:url';
import {transform, version} from '@swc/core';

const input = new URL('../src/common/webpack/fallback-controller.ts', import.meta.url);
const output = new URL('../src/common/webpack/fallback-runtime-source.ts', import.meta.url);
const options = {
    jsc: {parser: {syntax: 'typescript'}, target: 'es2017', externalHelpers: false},
    module: {type: 'commonjs'},
    sourceMaps: false,
};

await generate();

if (process.argv.includes('--watch')) {
    let pending = Promise.resolve();
    watch(fileURLToPath(new URL('.', input)), (_event, filename) => {
        if (filename !== 'fallback-controller.ts') return;
        pending = pending.then(generate).catch((error) => {
            process.stderr.write(`${error.stack || error}\n`);
            process.exitCode = 1;
        });
    });
}

async function generate() {
    const [source, generator] = await Promise.all([
        readFile(input, 'utf8'),
        readFile(new URL(import.meta.url), 'utf8'),
    ]);
    const hash = createHash('sha256')
        .update(source + generator + JSON.stringify(options) + version)
        .digest('hex');
    const header = `// Generated by scripts/build-fallback-runtime.mjs. Do not edit.\n// Input: ${hash}\n`;
    const previous = await readFile(output, 'utf8').catch((error) => {
        if (error.code === 'ENOENT') return '';
        throw error;
    });

    if (previous.startsWith(header)) return;

    const {code} = await transform(source, options);
    const runtime = `(function () {\nvar exports = {};\n${code}\nreturn exports;\n})()`;
    await writeFile(
        output,
        `${header}export const fallbackRuntimeSource: string = ${JSON.stringify(runtime)};\n`,
    );
}
